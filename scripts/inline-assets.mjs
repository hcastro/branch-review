// Inlines the rendered page's stylesheets into src/rendered/assets.generated.ts,
// with the sha256 the page's Content-Security-Policy allows them by. The
// pages load nothing, so every byte of style rides inside them, and the hash
// is computed here once rather than at every render.
//
//   node scripts/inline-assets.mjs           write the module if it changed
//   node scripts/inline-assets.mjs --check   exit 1 if the module is stale

import fs from 'node:fs';
import {createHash} from 'node:crypto';

const root = new URL('../', import.meta.url);
const target = new URL('src/rendered/assets.generated.ts', root);

// The MIT notice travels with the copy of github-markdown-css in every page.
const NOTICE = '/*! github-markdown-css 5.9.0 | MIT License | Copyright (c) Sindre Sorhus <sindresorhus@gmail.com> (https://sindresorhus.com) */';

function read(relative) {
  return fs.readFileSync(new URL(relative, root), 'utf8');
}

function generate() {
  const css = [NOTICE, read('src/rendered/assets/github-markdown.css'), read('src/rendered/assets/page.css')].join('\n');
  if (css.includes('</style')) throw new Error('a stylesheet contains </style');
  const hash = createHash('sha256').update(css).digest('base64');
  return [
    '// Generated by scripts/inline-assets.mjs from src/rendered/assets. Edit those',
    '// files and run the script (pnpm build runs it first; pnpm test fails',
    '// while this file is stale).',
    '',
    `export const PAGE_CSS = ${JSON.stringify(css)};`,
    '',
    '/** The CSP source that allows PAGE_CSS: its sha256, base64. */',
    `export const PAGE_CSS_HASH = 'sha256-${hash}';`,
    '',
  ].join('\n');
}

const next = generate();
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (current !== next) {
    process.stdout.write('src/rendered/assets.generated.ts is stale: run node scripts/inline-assets.mjs\n');
    process.exit(1);
  }
} else if (current !== next) {
  fs.writeFileSync(target, next);
}
