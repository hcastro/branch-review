// Inlines the rendered page's stylesheets and its script into
// src/rendered/assets.generated.ts, each with the sha256 the page's
// Content-Security-Policy allows it by. The pages load nothing, so every
// byte of style and script rides inside them, and the hashes are computed
// here once rather than at every render. The script is
// src/rendered/client/main.ts, bundled by esbuild into one IIFE.
//
//   node scripts/inline-assets.mjs           write the module if it changed
//   node scripts/inline-assets.mjs --check   exit 1 if the module is stale

import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {buildSync} from 'esbuild';

const root = new URL('../', import.meta.url);
const target = new URL('src/rendered/assets.generated.ts', root);

// The MIT notice travels with the copy of github-markdown-css in every page.
const NOTICE = '/*! github-markdown-css 5.9.0 | MIT License | Copyright (c) Sindre Sorhus <sindresorhus@gmail.com> (https://sindresorhus.com) */';

function read(relative) {
  return fs.readFileSync(new URL(relative, root), 'utf8');
}

// The declarations of the one rule that opens with `opening`, braces
// excluded. Both stylesheets keep their palettes in flat blocks.
function declarations(css, opening, file) {
  const at = css.indexOf(opening);
  if (at < 0) throw new Error(`${file}: no block opening with ${JSON.stringify(opening)}`);
  const start = at + opening.length;
  const end = css.indexOf('}', start);
  return css.slice(start, end).trim();
}

// The theme switch on the page forces light or dark whatever the system
// says. Both stylesheets pick their palette by prefers-color-scheme, so the
// forced palettes are their own blocks again, under `data-theme` on the
// root, derived here so they can't drift from the originals.
function forcedThemes(github, chrome) {
  const githubDark = declarations(github, '@media (prefers-color-scheme: dark) {\n  .markdown-body, [data-theme="dark"] {', 'github-markdown.css');
  const githubLight = declarations(github, '@media (prefers-color-scheme: light) {\n  .markdown-body, [data-theme="light"] {', 'github-markdown.css');
  const chromeLight = declarations(chrome, ':root {', 'page.css');
  const chromeDark = declarations(chrome, '@media (prefers-color-scheme: dark) {\n  :root {', 'page.css');
  const scheme = (block, name) => block.replace(/color-scheme: light dark;/, `color-scheme: ${name};`);
  return [
    '/* Forced themes, generated from the palettes above by scripts/inline-assets.mjs. */',
    `:root[data-theme="light"] {\n  ${scheme(chromeLight, 'light')}\n}`,
    `:root[data-theme="dark"] {\n  color-scheme: dark;\n  ${chromeDark}\n}`,
    `:root[data-theme="light"] .markdown-body {\n  ${githubLight}\n}`,
    `:root[data-theme="dark"] .markdown-body {\n  ${githubDark}\n}`,
  ].join('\n');
}

function script() {
  const built = buildSync({
    entryPoints: [fileURLToPath(new URL('src/rendered/client/main.ts', root))],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome111', 'safari16'],
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    write: false,
  });
  const code = built.outputFiles[0].text.trimEnd();
  if (/<\/script|<!--/i.test(code)) throw new Error('the page script contains </script or <!--');
  return code;
}

function sha256(text) {
  return `sha256-${createHash('sha256').update(text).digest('base64')}`;
}

function generate() {
  const github = read('src/rendered/assets/github-markdown.css');
  const chrome = read('src/rendered/assets/page.css');
  const css = [NOTICE, github, chrome, forcedThemes(github, chrome)].join('\n');
  if (css.includes('</style')) throw new Error('a stylesheet contains </style');
  const js = script();
  return [
    '// Generated by scripts/inline-assets.mjs from src/rendered/assets and',
    '// src/rendered/client. Edit those files and run the script (pnpm build',
    '// runs it first; pnpm test fails while this file is stale).',
    '',
    `export const PAGE_CSS = ${JSON.stringify(css)};`,
    '',
    '/** The CSP source that allows PAGE_CSS: its sha256, base64. */',
    `export const PAGE_CSS_HASH = '${sha256(css)}';`,
    '',
    `export const PAGE_SCRIPT = ${JSON.stringify(js)};`,
    '',
    '/** The CSP source that allows PAGE_SCRIPT: its sha256, base64. */',
    `export const PAGE_SCRIPT_HASH = '${sha256(js)}';`,
    '',
  ].join('\n');
}

const next = generate();
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (current !== next) {
    process.stdout.write('src/rendered/assets.generated.ts is stale: run node scripts/inline-assets.mjs\n');
    process.exit(1);
  }
} else if (current !== next) {
  fs.writeFileSync(target, next);
}
